"""Render docs/ml-report.md from training results (numbers are never hand-written)."""
from __future__ import annotations

from datetime import date
from pathlib import Path

HEADER = """# ML Report — Dental-IQ Phase 2

> **All models here are trained and evaluated on SYNTHETIC data** generated by
> `backend/scripts/seed.py`. The metrics show how well each model recovers the
> assumptions built into that generator. **They say nothing about real-world clinical or
> academic performance.** Real deployment needs real, consented, de-identified data,
> prospective validation and ethics approval.

Regenerate with `cd backend && python -m ml.train` (re-run after `python -m scripts.seed --reset`).
Generated: {today}.
"""


def _pr(m: dict) -> str:
    return f"{m['precision']:.2f} / {m['recall']:.2f} (flagged {m['flagged']}, TP {m['true_positives']})"


def oral_section(b: dict) -> str:
    cv, abl = b["metrics"]["cv5"], b["metrics"]["cv5_without_lesion_feature"]
    coef_rows = "\n".join(
        f"| {name} | {c:+.2f} | {pow(2.718281828, c):.2f}× |" for name, c in zip(b["features"], b["coef"])
    )
    return f"""
## 1. Oral cancer / PMD risk screening

**Question:** given a patient's demographics, habits, taluka and whether a mucosal lesion has been
observed, how likely is a potentially malignant disorder (OSMF, leukoplakia, lesion suspicious for
malignancy)?

| Item | Value |
|---|---|
| Model | L2 logistic regression (`C=1.0`), scikit-learn |
| Unit / population | adult patients (18+) with ≥1 submitted/approved case |
| Training rows | {b['n_train']} (PMD-positive: {b['n_positive']}, {b['n_positive'] / b['n_train'] * 100:.1f}%) |
| Label | any PMD diagnosis, same keyword definition as the analytics (`services/clinical_terms.py`) |
| Features | age (decades above 40), male, current/former smokeless tobacco (gutkha/khaini/mishri), current/former smoking, current alcohol, habit duration, rural-belt taluka (taluka-derived), lesion observed |
| Risk levels | Low < {b['thresholds']['medium']:.2f} ≤ Medium < {b['thresholds']['high']:.2f} ≤ High |
| Artifact | `backend/ml/artifacts/oral_risk.joblib` (v{b['version']}) |

### Metrics (5-fold stratified cross-validation, out-of-fold predictions)

| Model | ROC AUC | Precision / recall @ Medium+ | Precision / recall @ High |
|---|---|---|---|
| Full model | **{cv['auc']}** | {_pr(cv['at_medium'])} | {_pr(cv['at_high'])} |
| Ablation: without *lesion observed* | {abl['auc']} | {_pr(abl['at_medium'])} | {_pr(abl['at_high'])} |

The *lesion observed* feature is partly label-adjacent: leukoplakia cases record a lesion finding
in the same visit. The ablation row shows the signal that comes from **habits and demographics alone**,
which is the honest estimate for screening a patient **before** a lesion is charted.

### Coefficients (log-odds; odds multiplier relative to the reference patient)

Reference patient: 40-year-old woman, never used tobacco/alcohol, urban taluka, no lesion.

| Feature | Coefficient | Odds × |
|---|---|---|
| (intercept) | {b['intercept']:+.2f} | — |
{coef_rows}

### Explainability
The model is linear in log-odds, so every prediction is decomposed **exactly** into per-factor
contributions (`coef × value`). `POST /api/patients/{{id}}/risk-screening` returns the top factors with
their odds multipliers plus a rule-based suggested action (refer for biopsy, cessation counselling, recall).
"""


def student_section(b: dict) -> str:
    ev = b.get("evaluation")
    coef_rows = "\n".join(f"| {n} | {c:+.2f} |" for n, c in zip(b["features"], b["coef"]))
    if ev:
        eval_rows = "\n".join(
            f"| {name} | {m['precision']:.2f} | {m['recall']:.2f} | {m['f1']:.2f} | {m['flagged']} | {m['true_positives']} |"
            for name, m in (("Rules only", ev["rules"]), ("Model only (score ≥ 0.5)", ev["model"]),
                            ("**Hybrid (final alert)**", ev["hybrid"]))
        )
        missed = ", ".join(ev["missed"]) or "none"
        extra = ", ".join(ev["false_alarms"]) or "none"
        eval_md = f"""
### Evaluation against the 10 deliberately at-risk seeded students

Ground truth comes from the seed's hidden student profiles (`ml/artifacts/seed_ground_truth.json`).
It is **never stored in the database and never used for training**.

| Detector | Precision | Recall | F1 | Flagged | True positives |
|---|---|---|---|---|---|
{eval_rows}

- Ground-truth at-risk students: {ev['positives']} of {ev['students']}.
- Missed by the hybrid alert: {missed}
- Flagged but not designed at-risk: {extra}
"""
    else:
        eval_md = "\n*(No seed ground-truth file found — evaluation skipped.)*\n"

    return f"""
## 2. Explainable at-risk student alerts

| Item | Value |
|---|---|
| Unit | student (all years), features computed as of training day |
| Features | attendance % (last 12 weeks), attendance trend (last 4 weeks minus weeks 5–12), marks average %, marks trend (latest exam minus first, per subject), clinical quota pace vs cohort median (clinical years), case rejection rate |
| Rules | transparent thresholds, e.g. attendance < 75% (DCI requirement), drop ≥ 10 points, marks < 50%, pace < 60% of cohort median, rejection rate > 20% |
| Model | L2 logistic regression on standardised features (`class_weight="balanced"`) |
| Labels for training | **weak supervision**: a student is labelled at-risk if any *critical* rule fires. Real deployments should use historical outcomes (detained / failed / repeated year) instead. |
| Final alert (hybrid) | High = critical rule **or** score ≥ 0.7 · Medium = any rule **or** score ≥ 0.4 · otherwise Low |
| Artifact | `backend/ml/artifacts/student_risk.joblib` |
| Training rows | {b['n_train']} (weak positives: {b['n_positive']}) |

The model adds a **continuous, comparable score** and catches combinations of several "almost" signals
that no single rule fires on. The rules supply the plain-language **reasons**; the model's per-feature
contributions are shown alongside them.
{eval_md}
### Model coefficients (standardised features)

| Feature | Coefficient |
|---|---|
{coef_rows}
"""


def write_report(results: dict, path: Path) -> None:
    parts = [HEADER.format(today=date.today().isoformat())]
    if "oral_risk" in results:
        parts.append(oral_section(results["oral_risk"]))
    if "student_risk" in results:
        parts.append(student_section(results["student_risk"]))
    parts.append("""
## Limitations
- Synthetic, single-institution-style data; prevalences and effect sizes are generator assumptions.
- Small positive counts give wide confidence intervals; metrics will move with a different seed.
- Weak-supervision labels for the student model partly encode the same rules used in the hybrid.
- Models are deliberately simple and fully inspectable; no black-box scores are shown without reasons.
""")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(parts), encoding="utf-8")
