"""Oral cancer / potentially-malignant-disorder (PMD) risk screening.

Model: L2-regularised logistic regression on a handful of interpretable features. Because
the model is linear in log-odds, every prediction decomposes exactly into per-factor
contributions relative to a *reference patient* (40-year-old woman, never used tobacco or
alcohol, urban taluka, no lesion observed) -- which is what the UI shows.

Label: the patient has a PMD diagnosis (OSMF, leukoplakia or lesion suspicious for malignancy)
in any submitted/approved case -- using the same definition as the analytics module.

SYNTHETIC DATA: the training data are generated by scripts/seed.py. Metrics describe how well
the model recovers the seed's generative assumptions, NOT real-world clinical performance.
"""
from __future__ import annotations

from collections import defaultdict
from dataclasses import dataclass
from datetime import datetime, timezone

import numpy as np
from sklearn.linear_model import LogisticRegression
from sklearn.model_selection import StratifiedKFold, cross_val_predict
from sqlmodel import Session, select

from app.models import Case, Patient, ToothFinding
from app.models.enums import HabitStatus, Sex, Taluka, ToothCondition
from app.services.analytics import IN_SCOPE_STATUSES
from app.services.clinical_terms import is_pmd_diagnosis
from ml.common import auc, load_bundle, save_bundle, sigmoid, threshold_metrics

MODEL_NAME = "oral_risk"
MODEL_VERSION = "1.0"

# Talukas treated as the rural belt (higher smokeless-tobacco use). Kept in the model
# as a taluka-derived indicator rather than 12 sparse one-hot columns.
RURAL_TALUKAS = frozenset({Taluka.sattari, Taluka.sanguem, Taluka.canacona, Taluka.dharbandora,
                           Taluka.quepem, Taluka.pernem, Taluka.bicholim})

#: (feature, human label). Reference value for every feature is 0.
FEATURES: list[tuple[str, str]] = [
    ("age_decades", "Age (per decade above 40)"),
    ("male", "Male sex"),
    ("smokeless_current", "Current gutkha / smokeless tobacco use"),
    ("smokeless_former", "Former gutkha / smokeless tobacco use"),
    ("smoking_current", "Current smoking"),
    ("smoking_former", "Former smoking"),
    ("alcohol_current", "Current alcohol use"),
    ("habit_decades", "Habit duration (per 10 years)"),
    ("rural_taluka", "Lives in a rural-belt taluka"),
    ("lesion_observed", "Oral mucosal lesion observed"),
]
FEATURE_NAMES = [f for f, _ in FEATURES]
LABELS = dict(FEATURES)

THRESHOLDS = {"medium": 0.15, "high": 0.40}
MIN_AGE = 18


@dataclass
class PatientFeatures:
    values: dict[str, float]

    def vector(self, names: list[str] = FEATURE_NAMES) -> list[float]:
        return [self.values[n] for n in names]


def featurize(patient: Patient, lesion_observed: bool) -> PatientFeatures:
    return PatientFeatures({
        "age_decades": (patient.age - 40) / 10,
        "male": float(patient.sex == Sex.male),
        "smokeless_current": float(patient.smokeless_tobacco == HabitStatus.current),
        "smokeless_former": float(patient.smokeless_tobacco == HabitStatus.former),
        "smoking_current": float(patient.tobacco_smoking == HabitStatus.current),
        "smoking_former": float(patient.tobacco_smoking == HabitStatus.former),
        "alcohol_current": float(patient.alcohol == HabitStatus.current),
        "habit_decades": min(patient.habit_duration_years or 0, 40) / 10,
        "rural_taluka": float(patient.taluka in RURAL_TALUKAS),
        "lesion_observed": float(lesion_observed),
    })


def patient_history(session: Session, patient_ids: list[int] | None = None) -> tuple[dict[int, bool], dict[int, bool]]:
    """Return (has_pmd_diagnosis, lesion_recorded) per patient from in-scope cases."""
    stmt = select(Case.patient_id, Case.diagnosis).where(Case.status.in_(IN_SCOPE_STATUSES))
    les = (select(Case.patient_id).join(ToothFinding, ToothFinding.case_id == Case.id)
           .where(Case.status.in_(IN_SCOPE_STATUSES), ToothFinding.condition == ToothCondition.lesion))
    if patient_ids is not None:
        stmt = stmt.where(Case.patient_id.in_(patient_ids))
        les = les.where(Case.patient_id.in_(patient_ids))
    pmd: dict[int, bool] = defaultdict(bool)
    for pid, diagnosis in session.exec(stmt).all():
        pmd[pid] |= is_pmd_diagnosis(diagnosis)
    lesion = {pid: True for pid in session.exec(les).all()}
    return pmd, lesion


def build_dataset(session: Session) -> tuple[np.ndarray, np.ndarray, list[int]]:
    pmd, lesion = patient_history(session)
    patients = session.exec(select(Patient).where(Patient.age >= MIN_AGE)).all()
    rows = [p for p in patients if p.id in pmd]  # adults with at least one in-scope case
    X = np.array([featurize(p, lesion.get(p.id, False)).vector() for p in rows], dtype=float)
    y = np.array([int(pmd[p.id]) for p in rows])
    return X, y, [p.id for p in rows]


def _model() -> LogisticRegression:
    return LogisticRegression(C=1.0, max_iter=2000)


def _cv_eval(X: np.ndarray, y: np.ndarray) -> dict:
    cv = StratifiedKFold(n_splits=5, shuffle=True, random_state=42)
    prob = cross_val_predict(_model(), X, y, cv=cv, method="predict_proba")[:, 1]
    return {
        "auc": auc(y, prob),
        "at_medium": threshold_metrics(y, prob, THRESHOLDS["medium"]),
        "at_high": threshold_metrics(y, prob, THRESHOLDS["high"]),
    }


def train(session: Session) -> dict:
    X, y, _ids = build_dataset(session)
    if len(set(y.tolist())) < 2 or y.sum() < 5:
        raise ValueError("Not enough positive PMD cases to train the oral-risk model")

    cv = _cv_eval(X, y)
    # Ablation: how much signal remains without the (partly label-adjacent) lesion feature?
    no_lesion = [i for i, n in enumerate(FEATURE_NAMES) if n != "lesion_observed"]
    cv_no_lesion = _cv_eval(X[:, no_lesion], y)

    model = _model().fit(X, y)
    bundle = {
        "name": MODEL_NAME,
        "version": MODEL_VERSION,
        "trained_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "features": FEATURE_NAMES,
        "coef": model.coef_[0].tolist(),
        "intercept": float(model.intercept_[0]),
        "thresholds": THRESHOLDS,
        "n_train": int(len(y)),
        "n_positive": int(y.sum()),
        "metrics": {"cv5": cv, "cv5_without_lesion_feature": cv_no_lesion},
        "model": model,
    }
    save_bundle(MODEL_NAME, bundle)
    return bundle


# --------------------------------------------------------------------------- inference

def risk_level(prob: float, thresholds: dict = THRESHOLDS) -> str:
    if prob >= thresholds["high"]:
        return "High"
    if prob >= thresholds["medium"]:
        return "Medium"
    return "Low"


def explain(bundle: dict, features: PatientFeatures) -> dict:
    """Exact decomposition of the log-odds into per-feature contributions."""
    coefs = dict(zip(bundle["features"], bundle["coef"]))
    logit = bundle["intercept"]
    factors = []
    for name in bundle["features"]:
        x = features.values[name]
        contribution = coefs[name] * x
        logit += contribution
        if abs(contribution) >= 0.05:
            factors.append({
                "feature": name,
                "label": LABELS[name],
                "value": round(x, 2),
                "contribution": round(contribution, 3),
                "odds_multiplier": round(float(np.exp(contribution)), 2),
                "direction": "increases" if contribution > 0 else "decreases",
            })
    factors.sort(key=lambda f: -abs(f["contribution"]))
    return {
        "probability": sigmoid(logit),
        "baseline_probability": sigmoid(bundle["intercept"]),
        "factors": factors,
    }


def suggested_actions(level: str, patient: Patient, lesion: bool, known_pmd: bool) -> tuple[str, list[str]]:
    actions: list[str] = []
    if known_pmd:
        headline = "Existing PMD diagnosis on record: keep the patient on the Oral Medicine follow-up / biopsy pathway."
    elif level == "High":
        headline = ("Refer to Oral Medicine for a detailed mucosal examination"
                    + (" and biopsy of the observed lesion." if lesion else "; biopsy any lesion persisting > 2 weeks."))
    elif level == "Medium":
        headline = "Screen the oral mucosa at every visit and review in 3 months."
    else:
        headline = "Routine oral cancer screening at recall visits."

    if HabitStatus.current in (patient.smokeless_tobacco, patient.tobacco_smoking):
        actions.append("Brief tobacco-cessation counselling (5 A's); offer referral to a tobacco cessation centre.")
    if patient.alcohol == HabitStatus.current:
        actions.append("Advise reducing alcohol; combined tobacco + alcohol use multiplies risk.")
    if lesion and not known_pmd:
        actions.append("Document lesion site and size; consider toluidine-blue staining before biopsy.")
    if level == "Low" and not actions:
        actions.append("Reinforce no-tobacco advice.")
    return headline, actions


def screen(session: Session, patient: Patient, lesion_override: bool | None = None) -> dict:
    bundle = load_bundle(MODEL_NAME)
    if bundle is None:
        raise FileNotFoundError("Oral-risk model has not been trained. Run `python -m ml.train` in backend/.")

    pmd, lesion_hist = patient_history(session, [patient.id])
    recorded = lesion_hist.get(patient.id, False)
    lesion = recorded if lesion_override is None else (lesion_override or recorded)
    lesion_source = "override" if lesion_override and not recorded else ("recorded" if recorded else "none")

    result = explain(bundle, featurize(patient, lesion))
    prob = result["probability"]
    level = risk_level(prob, bundle["thresholds"])
    known_pmd = pmd.get(patient.id, False)
    headline, actions = suggested_actions(level, patient, lesion, known_pmd)

    notes = []
    model_level = level
    if known_pmd and level != "High":
        # A confirmed diagnosis outranks a risk-factor estimate; say so explicitly.
        level = "High"
        notes.append(f"Risk level set to High because a PMD diagnosis is on record "
                     f"(model estimate from risk factors alone: {model_level}, {prob * 100:.1f}%).")
    if patient.age < MIN_AGE:
        notes.append("Model trained on adults (18+); interpret with caution for younger patients.")
    return {
        "patient_id": patient.id,
        "probability": round(prob, 3),
        "risk_percent": round(prob * 100, 1),
        "risk_level": level,
        "model_risk_level": model_level,
        "baseline_probability": round(result["baseline_probability"], 3),
        "factors": result["factors"],
        "lesion_observed": lesion,
        "lesion_source": lesion_source,
        "known_pmd_diagnosis": known_pmd,
        "suggested_action": headline,
        "additional_actions": actions,
        "notes": notes,
        "model": {
            "version": bundle["version"],
            "trained_at": bundle["trained_at"],
            "auc_cv": bundle["metrics"]["cv5"]["auc"],
            "n_train": bundle["n_train"],
            "thresholds": bundle["thresholds"],
        },
        "disclaimer": "Screening aid trained on synthetic data. Not a diagnosis; clinical judgement prevails.",
    }
